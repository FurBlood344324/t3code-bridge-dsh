function homeDir(env = process.env) {
  const raw = env && typeof env.HOME === "string" ? env.HOME.trim() : "";
  return isAbsolute(raw) ? resolve(raw) : resolve(homedir());
}

/** `<XDG_CONFIG_HOME or ~/.config>/t3code-bridge-dsh/routes.yml`, always absolute. */
export function overlayPath(env = process.env) {
  const xdg = env && typeof env.XDG_CONFIG_HOME === "string" ? env.XDG_CONFIG_HOME.trim() : "";
  // XDG spec: a relative XDG_CONFIG_HOME is invalid and ignored (it would resolve against T3's project cwd).
  const base = isAbsolute(xdg) ? resolve(xdg) : join(homeDir(env), ".config");
  return join(base, "t3code-bridge-dsh", "routes.yml");
}

// A plain YAML scalar is legal unless it starts with an indicator, or carries `: ` / ` #`.
const INDICATOR_START_RE = /^[-?:,\[\]{}#&*!|>'"%@`]/;
const BREAKS_PLAIN_RE = /:\s|:$|\s#/;

/**
 * Quote a YAML scalar only when the plain form would change meaning, so the overlay reads like
 * the operator's own `cordis.patch.yml`: `baseURL: https://...` and `name: DS V4.1 Flash` plain,
 * `name: "@deepseek-ai/dsh-llm-pi-ai"` quoted. Secrets never pass through here (only names/shapes).
 */
function scalar(value) {
  const text = String(value);
  const needsQuotes =
    text === "" || /^\s|\s$/.test(text) || INDICATOR_START_RE.test(text) || BREAKS_PLAIN_RE.test(text);
  return needsQuotes ? `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"` : text;
}

function assertObject(value, label) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`renderOverlay: ${label} must be an object`);
  }
}

/**
 * Validate the route structure before rendering. Messages name fields, never values of keys.
 * @returns {{default: object, providers: object}}
 */
export function validateRoutes(routes) {
  assertObject(routes, "routes");
  assertObject(routes.providers, "routes.providers");
  const ids = Object.keys(routes.providers);
  if (ids.length === 0) throw new Error("renderOverlay: routes.providers is empty");
  for (const id of ids) {
    const provider = routes.providers[id];
    assertObject(provider, `routes.providers.${id}`);
    if (typeof provider.apiKeyEnv !== "string" || provider.apiKeyEnv.trim() === "") {
      throw new Error(`renderOverlay: routes.providers.${id}.apiKeyEnv is required`);
    }
    if (!Array.isArray(provider.models) || provider.models.length === 0) {
      throw new Error(`renderOverlay: routes.providers.${id}.models must be a non-empty array`);
    }
    for (const model of provider.models) {
      assertObject(model, `routes.providers.${id}.models[]`);
      if (typeof model.id !== "string" || model.id.trim() === "") {
        throw new Error(`renderOverlay: routes.providers.${id} has a model without an id`);
      }
    }
  }
  assertObject(routes.default, "routes.default");
  for (const field of ["provider", "model", "reasoningEffort"]) {
    if (typeof routes.default[field] !== "string" || routes.default[field].trim() === "") {
      throw new Error(`renderOverlay: routes.default.${field} is required`);
    }
  }
  const target = routes.providers[routes.default.provider];
  if (!target) {
    throw new Error(`renderOverlay: routes.default.provider "${routes.default.provider}" is not in routes.providers`);
  }
  if (!target.models.some((model) => model.id === routes.default.model)) {
    throw new Error(
      `renderOverlay: routes.default.model "${routes.default.model}" is not offered by provider "${routes.default.provider}"`,
    );
  }
  return routes;
}

/**
 * Render the patch overlay as YAML text (a top-level array of two loader patch entries).
 * Output is a pure function of the routes: same routes, byte-identical text.
 */
export function renderOverlay(routes = DEFAULT_ROUTES) {
  const { default: fallback, providers } = validateRoutes(routes);
  const lines = [ROUTES_HEADER, `- id: ${LLM_ENTRY_ID}`, `  name: "${LLM_ENTRY_NAME}"`, "  config:", "    providers:"];

  for (const id of Object.keys(providers)) {
    const provider = providers[id];
    lines.push(`      ${scalar(id)}:`);
    if (provider.displayName) lines.push(`        displayName: ${scalar(provider.displayName)}`);
    lines.push(`        apiKeyEnv: ${scalar(provider.apiKeyEnv)}`);
    if (provider.api) lines.push(`        api: ${scalar(provider.api)}`);
    if (provider.baseURL) lines.push(`        baseURL: ${scalar(provider.baseURL)}`);
    lines.push("        models:");
    for (const model of provider.models) {
      lines.push(`          - id: ${scalar(model.id)}`);
      if (model.name) lines.push(`            name: ${scalar(model.name)}`);
      if (model.contextWindow) lines.push(`            contextWindow: ${model.contextWindow}`);
      const input = Array.isArray(model.input) ? model.input : [];
      if (input.length > 0) {
        lines.push("            input:");
        for (const item of input) lines.push(`              - ${scalar(item)}`);
      }
      const efforts = model.reasoningEfforts && typeof model.reasoningEfforts === "object" ? model.reasoningEfforts : {};
      const levels = Object.keys(efforts);
      if (levels.length > 0) {
        lines.push("            reasoningEfforts:");
        for (const level of levels) lines.push(`              ${scalar(level)}: ${scalar(efforts[level])}`);
      }
    }
    const compat = provider.compat && typeof provider.compat === "object" ? provider.compat : COMPAT;
    lines.push("        compat:");
    for (const key of Object.keys(compat)) lines.push(`          ${key}: ${yamlLiteral(compat[key])}`);
  }

  lines.push(
    `- id: ${DEFAULT_MODEL_ENTRY_ID}`,
    `  name: "${DEFAULT_MODEL_ENTRY_NAME}"`,
    `  config: { provider: ${scalar(fallback.provider)}, model: ${scalar(fallback.model)}, reasoningEffort: ${scalar(
      fallback.reasoningEffort,
    )} }`,
  );
  return `${lines.join("\n")}\n`;
}

function yamlLiteral(value) {
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  if (value === null || value === undefined) return "null";
  return scalar(value);
}

function readIfExists(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

/**
 * Write the overlay atomically (temp file in the same directory + rename).
 * An unchanged file is not rewritten, so callers can report `changed: false` honestly.
 * @returns {{changed: boolean}}
 */
export function writeOverlay(path, { dryRun = false, routes = DEFAULT_ROUTES } = {}) {
  if (typeof path !== "string" || path.trim() === "") {
    throw new Error("writeOverlay: path is required");
  }
  const target = resolve(path);
  const text = renderOverlay(routes);
  if (readIfExists(target) === text) return { changed: false };
  if (dryRun) return { changed: true };

  const dir = dirname(target);
  mkdirSync(dir, { recursive: true });
  const temp = join(dir, `.${process.pid}-${Date.now()}-${Math.random().toString(16).slice(2)}.yml.tmp`);
  try {
    writeFileSync(temp, text, "utf8");
    renameSync(temp, target);
  } catch (err) {
    try {
      rmSync(temp, { force: true });
    } catch {
      // the temp file is ours; a failed cleanup must not hide the write error
    }
    throw err;
  }
  return { changed: true };
}
