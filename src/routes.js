// Model routes for a dsh ACP profile: one YAML patch overlay, rendered deterministically.
//
// The overlay is a second `--patch` layer on top of the variant's own `cordis.patch.yml`. It
// carries the routes the operator fixed (2026-11-13): opendesign `deepseek-v4.1-flash` at
// reasoning `max` by default, command-code and opencode-go as selectable backups. Provider
// shapes follow ~/.dsh/profiles/dsbot/cordis.patch.yml. Only env var *names* are written here:
// key values are the launcher's business and never reach a file (see src/secrets.js).

import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, isAbsolute, join, resolve } from "node:path";

/** First line of every generated overlay. */
export const ROUTES_HEADER =
  "# generated by t3code-bridge-dsh; contains env var names only, never keys";

export const LLM_ENTRY_ID = "llm-pi-ai";
export const LLM_ENTRY_NAME = "@deepseek-ai/dsh-llm-pi-ai";
export const DEFAULT_MODEL_ENTRY_ID = "agent-default-model";
export const DEFAULT_MODEL_ENTRY_NAME = "@deepseek-ai/dsh-agent-default-model";

/** Provider render order (stable output). */
export const PROVIDER_ORDER = Object.freeze(["opendesign", "command-code", "opencode-go"]);

/** Compat block every provider in this stack uses. */
const COMPAT = Object.freeze({
  supportsDeveloperRole: false,
  supportsStore: false,
  maxTokensField: "max_tokens",
  requiresReasoningContentOnAssistantMessages: true,
});

function freezeDeep(value) {
  if (value && typeof value === "object") {
    for (const key of Object.keys(value)) freezeDeep(value[key]);
    Object.freeze(value);
  }
  return value;
}

/** `["medium","high","max"]` -> `{medium: "medium", high: "high", max: "max"}` (key order kept). */
function reasoningEfforts(...levels) {
  const efforts = {};
  for (const level of levels) efforts[level] = level;
  return Object.freeze(efforts);
}

function modelDef({ id, name, contextWindow = 1000000, input, levels }) {
  return Object.freeze({
    id,
    name,
    contextWindow,
    input: Object.freeze(input.slice()),
    reasoningEfforts: reasoningEfforts(...levels),
  });
}

