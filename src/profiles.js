// Discovery of dsh profiles under <DSH_HOME>/profiles.
//
// A dsh profile is a directory holding a package.json with `dsh.profile.bundles` plus an optional
// `cordis.patch.yml`. A profile runs at most one *app* bundle (web-app, headless, ds-bot, tui, ...);
// everything else in the list is a plugin bundle. The ACP variant of a profile swaps the app bundle
// for @deepseek-ai/dsh-acp-app and keeps every plugin bundle and its order.
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

/**
 * App bundles: at most one per profile, and no ACP variant carries any. Callers that need a different
 * set pass `appBundles` to the planning functions instead of mutating this list.
 */
export const APP_BUNDLES = [
  "@deepseek-ai/dsh-web-app",
  "@deepseek-ai/dsh-headless",
  "@deepseek-ai/dsh-sdk-app",
  "@deepseek-ai/dsh-sdk-minimal",
  "ds-bot",
  "@deepseek-harness-tui/dsh-tui",
  "@open-design/dsh-runtime",
];

/** The ACP app bundle every generated variant runs. */
export const ACP_BUNDLE = "@deepseek-ai/dsh-acp-app";

/** Base bundle; the ACP app is inserted directly after it. */
export const BASE_BUNDLE = "@deepseek-ai/dsh-base";

/** Ownership marker file this tool writes into every directory it creates. */
export const VARIANT_MARKER = ".t3code-bridge-dsh";

/** The shipped ACP profile: the reference implementation, never a bridge source. */
export const SHIPPED_ACP_PROFILE = "acp";

/** Variant profile name for a source profile. */
export function variantName(name) {
  return `${name}-acp`;
}

/** Marker header line prepended to a generated `cordis.patch.yml`. */
export function patchHeader(name) {
  return `# generated by t3code-bridge-dsh from profile ${name}; run \`t3code-bridge-dsh sync\``;
}

/** dsh home directory: `$DSH_HOME` or `~/.dsh`, always absolute. */
export function dshHome(env = process.env) {
  const raw = env && typeof env.DSH_HOME === "string" ? env.DSH_HOME.trim() : "";
  return resolve(raw || join(homedir(), ".dsh"));
}

function statOrNull(path) {
  try {
    return statSync(path);
  } catch {
    return null;
  }
}

/** True for an existing path that resolves to a directory (symlinks followed). */
export function isDirectory(path) {
  const st = statOrNull(path);
  return Boolean(st && st.isDirectory());
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

/**
 * Read one profile directory.
 * @returns {{ pkg: object, bundles: string[] } | null} null when the directory is not a profile.
 */
export function readProfile(dir) {
  const pkg = readJson(join(dir, "package.json"));
  const bundles = pkg && pkg.dsh && pkg.dsh.profile && pkg.dsh.profile.bundles;
  if (!Array.isArray(bundles)) return null;
  return { pkg, bundles: bundles.filter((bundle) => typeof bundle === "string") };
}

/**
 * What sits at `<home>/profiles/<name>-acp`: "absent" (nothing there), "owned" (this tool's variant,
 * carries VARIANT_MARKER) or "unowned" (something else: the caller must not overwrite it).
 */
export function variantState(name, { home = dshHome() } = {}) {
  const dir = join(home, "profiles", variantName(name));
  if (!existsSync(dir)) return "absent";
  return existsSync(join(dir, VARIANT_MARKER)) ? "owned" : "unowned";
}

/**
 * List profiles under `<home>/profiles`.
 * Directories without a usable package.json are skipped, as are dot-directories.
 * @returns {Array<{name: string, dir: string, bundles: string[], appBundles: string[],
 *   isVariant: boolean, variantName: string, variantExists: boolean}>}
 * `variantExists` is literal: anything at `<home>/profiles/<name>-acp` counts. `variantState` tells an
 * unowned directory (user data, never overwritten) from this tool's own variant.
 */
export function listProfiles({ home = dshHome() } = {}) {
  const profilesDir = join(home, "profiles");
  let entries;
  try {
    entries = readdirSync(profilesDir, { withFileTypes: true });
  } catch {
    return [];
  }

  const names = entries
    .map((entry) => entry.name)
    .filter((name) => !name.startsWith("."))
    .filter((name) => isDirectory(join(profilesDir, name)))
    .sort();

  const appSet = new Set(APP_BUNDLES);
  const profiles = [];
  for (const name of names) {
    const dir = join(profilesDir, name);
    const profile = readProfile(dir);
    if (!profile) continue;
    const variant = variantName(name);
    profiles.push({
      name,
      dir,
      bundles: profile.bundles.slice(),
      appBundles: profile.bundles.filter((bundle) => appSet.has(bundle)),
      isVariant: existsSync(join(dir, VARIANT_MARKER)),
      variantName: variant,
      // Literal existence: an unmarked directory of that name is reported here too, while
      // variantState("unowned") marks it as user data this tool must not claim or overwrite.
      variantExists: existsSync(join(profilesDir, variant)),
    });
  }
  return profiles;
}

/** One profile by name, or null. */
export function findProfile(name, { home = dshHome() } = {}) {
  return listProfiles({ home }).find((profile) => profile.name === name) || null;
}
