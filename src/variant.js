// Generates, applies, syncs and removes ACP variant profiles.
//
// A variant is a real, self-contained dsh profile directory (`<name>-acp`) whose only difference from
// its source is the app bundle: the app is replaced by @deepseek-ai/dsh-acp-app so `dsh --profile
// <name>-acp` speaks ACP over stdio. Plugin bundles, their order, dependencies and the cordis layers
// are inherited. The directory is owned by this tool and carries VARIANT_MARKER; without the marker we
// refuse to touch it.
import {
  lstatSync,
  mkdirSync,
  readFileSync,
  readlinkSync,
  renameSync,
  rmSync,
  symlinkSync,
  unlinkSync,
  writeFileSync,
  existsSync,
} from "node:fs";
import { join } from "node:path";
import {
  ACP_BUNDLE,
  APP_BUNDLES,
  BASE_BUNDLE,
  SHIPPED_ACP_PROFILE,
  VARIANT_MARKER,
  dshHome,
  listProfiles,
  patchHeader,
  variantName,
} from "./profiles.js";

function lstatOrNull(path) {
  try {
    return lstatSync(path);
  } catch {
    return null;
  }
}

function isSymlink(path) {
  const st = lstatOrNull(path);
  return Boolean(st && st.isSymbolicLink());
}

/** Directory exists and resolves to a dir (symlinks followed); false for a plain file. */
function dirExists(path) {
  const st = lstatOrNull(path);
  if (!st) return false;
  if (st.isSymbolicLink()) return existsSync(path);
  return st.isDirectory();
}

function readTextOrNull(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

function jsonText(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function withTrailingNewline(text) {
  return text.endsWith("\n") ? text : `${text}\n`;
}

/**
 * Bundles of the ACP variant: every app bundle out, the ACP app right after the base bundle.
 * Pure; the source list is not mutated.
 */
export function variantBundles(bundles, { appBundles = APP_BUNDLES } = {}) {
  const drop = new Set(appBundles);
  const kept = [];
  for (const bundle of bundles) {
    if (drop.has(bundle)) continue;
    if (bundle === ACP_BUNDLE) continue; // avoid a second copy when the source already carries one
    kept.push(bundle);
  }
  const baseAt = kept.indexOf(BASE_BUNDLE);
  if (baseAt >= 0) kept.splice(baseAt + 1, 0, ACP_BUNDLE);
  else kept.unshift(ACP_BUNDLE);
  return kept;
}

/** Generated patch yml: marker header + the source patch body (or an empty array). */
export function variantPatch(name, sourceText) {
  const header = patchHeader(name);
  let body = sourceText === null || sourceText === undefined ? "" : sourceText;
  // Never stack headers: a body that already starts with a generated header is reduced to its body.
  body = body.replace(/^# generated by t3code-bridge-dsh[^\n]*\n?/, "");
  // dsh expects a top-level YAML array; an absent or whitespace-only patch becomes `[]`.
  if (body.trim() === "") body = "[]\n";
  return `${header}\n${withTrailingNewline(body)}`;
}

/**
 * Plan the ACP variant of profile `name`. Pure: reads the source profile, writes nothing.
 * @returns {{ source: string, target: string, sourceDir: string, targetDir: string,
 *   packageJson: object, patchYml: string, actions: string[] }}
 */
export function planVariant(name, { home = dshHome(), appBundles = APP_BUNDLES } = {}) {
  if (typeof name !== "string" || name.trim() === "") {
    throw new Error("planVariant: profile name must be a non-empty string");
  }
  const profile = listProfiles({ home }).find((entry) => entry.name === name);
  if (!profile) {
    throw new Error(`planVariant: dsh profile "${name}" not found under ${join(home, "profiles")}`);
  }
  if (profile.isVariant) {
    throw new Error(`planVariant: "${name}" is itself an ACP variant and cannot be a source`);
  }
  if (name === SHIPPED_ACP_PROFILE) {
    throw new Error(`planVariant: "${name}" is the shipped ACP profile and needs no variant`);
  }

  const target = variantName(name);
  const targetDir = join(home, "profiles", target);

  const pkg = JSON.parse(readFileSync(join(profile.dir, "package.json"), "utf8"));
  const packageJson = structuredClone(pkg);
  packageJson.name = `dsh-profile-${target}`;
  packageJson.dsh = packageJson.dsh || {};
  packageJson.dsh.profile = packageJson.dsh.profile || {};
  packageJson.dsh.profile.bundles = variantBundles(profile.bundles, { appBundles });

  const patchYml = variantPatch(name, readTextOrNull(join(profile.dir, "cordis.patch.yml")));

  const actions = [];
  const targetState = lstatOrNull(targetDir);
  if (!targetState) actions.push(`create ${targetDir}`);
  else if (!dirExists(targetDir)) actions.push(`refuse: ${targetDir} exists and is not a directory`);
  else if (!existsSync(join(targetDir, VARIANT_MARKER))) {
    actions.push(`refuse: ${targetDir} exists without ${VARIANT_MARKER}`);
  }

  actions.push(`write ${join(targetDir, "package.json")} (bundles: ${packageJson.dsh.profile.bundles.join(", ")})`);
  actions.push(`write ${join(targetDir, "cordis.patch.yml")}`);

  const cordisSource = join(profile.dir, "cordis.yml");
  if (existsSync(cordisSource)) actions.push(`copy ${cordisSource} -> ${join(targetDir, "cordis.yml")}`);

  const modulesSource = join(profile.dir, "node_modules");
  if (existsSync(modulesSource)) {
    const link = join(targetDir, "node_modules");
    const current = isSymlink(link) ? readlinkSync(link) : null;
    if (current === modulesSource) actions.push(`keep symlink ${link} -> ${modulesSource}`);
    else if (current) actions.push(`replace symlink ${link} -> ${modulesSource}`);
    else actions.push(`link ${link} -> ${modulesSource}`);
  }

  actions.push(`write ${join(targetDir, VARIANT_MARKER)}`);

  return { source: name, target, sourceDir: profile.dir, targetDir, packageJson, patchYml, actions };
}

/** Write `content` to `path` only when it differs; atomic via temp file + rename. */
function writeTextIfChanged(path, content) {
  if (readTextOrNull(path) === content) return false;
  const tmp = `${path}.tmp-${process.pid}-${Date.now()}`;
  try {
    writeFileSync(tmp, content);
    renameSync(tmp, path);
  } catch (error) {
    try {
      unlinkSync(tmp);
    } catch {
      /* nothing to clean up */
    }
    throw error;
  }
  return true;
}

/** Point `<targetDir>/node_modules` at the source's node_modules; true when the link was (re)made. */
function linkNodeModules(sourceDir, targetDir) {
  const source = join(sourceDir, "node_modules");
  if (!existsSync(source)) return false;
  const link = join(targetDir, "node_modules");
  const st = lstatOrNull(link);
  if (st && st.isSymbolicLink()) {
    if (readlinkSync(link) === source) return false;
    unlinkSync(link);
  } else if (st) {
    // A real directory here means someone installed into the variant; never delete it.
    return false;
  }
  symlinkSync(source, link, "dir");
  return true;
}

/**
 * Apply a plan produced by planVariant.
 * Idempotent: a second run against an unchanged source reports `{created:false, updated:false}`.
 * @returns {{ created: boolean, updated: boolean, dir: string }}
 */
export function applyVariant(plan, { dryRun = false } = {}) {
  if (!plan || typeof plan !== "object" || !plan.targetDir) {
    throw new Error("applyVariant: expected a plan from planVariant");
  }
  const { source, sourceDir, targetDir, packageJson, patchYml } = plan;
  const existed = dirExists(targetDir);

  const targetStat = lstatOrNull(targetDir);
  if (targetStat && !existed) {
    throw new Error(`applyVariant: ${targetDir} exists and is not a directory`);
  }
  if (targetStat && targetStat.isSymbolicLink()) {
    // Never write through a symlinked profile dir: the marker check cannot vouch for the real target.
    throw new Error(`applyVariant: refusing to write through the symlink ${targetDir}`);
  }
  if (existed && !existsSync(join(targetDir, VARIANT_MARKER))) {
    throw new Error(
      `applyVariant: refusing to overwrite ${targetDir}: it exists without the ${VARIANT_MARKER} marker`,
    );
  }

  const files = new Map([
    [join(targetDir, "package.json"), jsonText(packageJson)],
    [join(targetDir, "cordis.patch.yml"), withTrailingNewline(patchYml)],
  ]);
  const cordisSource = join(sourceDir, "cordis.yml");
  if (existsSync(cordisSource)) {
    const text = readTextOrNull(cordisSource);
    if (text !== null) files.set(join(targetDir, "cordis.yml"), text);
  }

  const wouldChangeFiles = [...files].some(([path, content]) => readTextOrNull(path) !== content);
  const marker = join(targetDir, VARIANT_MARKER);
  const currentMarker = readTextOrNull(marker);
  const markerJson = currentMarker === null ? null : safeParse(currentMarker);
  const markerChanged = !markerJson || markerJson.source !== source;
  const wouldLink = existsSync(join(sourceDir, "node_modules")) && needsLink(sourceDir, targetDir);

  if (dryRun) {
    return { created: !existed, updated: existed && (wouldChangeFiles || markerChanged || wouldLink), dir: targetDir };
  }

  if (!existed) mkdirSync(targetDir, { recursive: true });

  let changed = false;
  for (const [path, content] of files) {
    if (writeTextIfChanged(path, content)) changed = true;
  }
  if (linkNodeModules(sourceDir, targetDir)) changed = true;
  if (markerChanged) {
    const createdAt = markerJson && markerJson.createdAt ? markerJson.createdAt : new Date().toISOString();
    if (writeTextIfChanged(marker, jsonText({ source, createdAt }))) changed = true;
  }

  return { created: !existed, updated: existed && changed, dir: targetDir };
}

function safeParse(text) {
  try {
    const value = JSON.parse(text);
    return value && typeof value === "object" ? value : null;
  } catch {
    return null;
  }
}

function needsLink(sourceDir, targetDir) {
  const source = join(sourceDir, "node_modules");
  const link = join(targetDir, "node_modules");
  const st = lstatOrNull(link);
  if (!st) return true;
  if (!st.isSymbolicLink()) return false; // real dir: leave it alone
  return readlinkSync(link) !== source;
}

/**
 * Remove the ACP variant of `name`. Only a directory carrying VARIANT_MARKER is removed; the source
 * profile is never touched and the node_modules symlink is unlinked, never followed.
 * @returns {{ removed: boolean }}
 */
export function removeVariant(name, { home = dshHome(), dryRun = false } = {}) {
  if (typeof name !== "string" || name.trim() === "") {
    throw new Error("removeVariant: profile name must be a non-empty string");
  }
  const sourceDir = join(home, "profiles", name);
  const targetDir = join(home, "profiles", variantName(name));
  if (targetDir === sourceDir) return { removed: false };

  const st = lstatOrNull(targetDir);
  if (!st || !dirExists(targetDir)) return { removed: false };
  if (!existsSync(join(targetDir, VARIANT_MARKER))) return { removed: false };
  if (dryRun) return { removed: true };

  if (st.isSymbolicLink()) {
    // A symlinked variant dir is dropped as a link only; nothing behind it is touched.
    unlinkSync(targetDir);
    return { removed: true };
  }

  const link = join(targetDir, "node_modules");
  if (isSymlink(link)) unlinkSync(link);
  rmSync(targetDir, { recursive: true, force: true });
  return { removed: true };
}

/** planVariant + applyVariant. */
export function syncVariant(name, { home = dshHome(), appBundles = APP_BUNDLES, dryRun = false } = {}) {
  const plan = planVariant(name, { home, appBundles });
  return applyVariant(plan, { dryRun });
}
